// Data types in Javascript 

// They are two types of Javascript Data Types. They are :-

// (1) Premitive Data types

// (2) Reference (or) Non- Premitive Data Types

// (1) Premitive Data Type 

// It stores single value in single memory 

// (1.1) String

// (1.2) Number

// (1.3) Boolean 

// (1.4) Undefined

// (1.5) BigInt 

// (1.6) Null

// (1.7) Symbol 

// (1.1) String:-

// A string or text string is a series of characters. 

// It can we written in single quotes ('') or double quotes ("")

// Example :- 

// Using Double Quotes ("") 

var name = "Mujasheer"

var color = "Green"

var carname = "Thar"

var mobile = "iphone"

var laptop = "Dell"

